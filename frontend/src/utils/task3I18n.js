export function translateTask3Label(lang = 'en', section, key) {
  return COPY[lang]?.[section]?.[key] ?? COPY.en?.[section]?.[key] ?? key
}

export function formatTask3Template(lang = 'en', section, key, vars = {}) {
  const template = translateTask3Label(lang, section, key)
  if (typeof template !== 'string') return template
  return template.replace(/\{(\w+)\}/g, (_, name) => String(vars[name] ?? `{${name}}`))
}

export function getTask3Copy(lang = 'en') {
  return COPY[lang] || COPY.en
}
